export function maxScore(screener: Screener): number {
  return screener.questions.length * 3;
}

export function bandFor(screener: Screener, score: number): ScreenerBand {
  const sorted = [...screener.bands].sort((a, b) => b.min - a.min);
  return sorted.find((band) => score >= band.min) ?? sorted[sorted.length - 1];
}

