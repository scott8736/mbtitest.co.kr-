/** 6명 라운드로빈(원형 배치). 5라운드 × 3경기 = 15쌍, 라운드마다 여섯 유형이 한 번씩 나옵니다 */
function roundRobinPairs(): Array<[CareerKey, CareerKey]> {
  const fixed = ORDER[0];
  let rest = ORDER.slice(1);
  const pairs: Array<[CareerKey, CareerKey]> = [];
  for (let round = 0; round < ORDER.length - 1; round++) {
    const line = [fixed, ...rest];
    for (let i = 0; i < line.length / 2; i++) pairs.push([line[i], line[line.length - 1 - i]]);
    rest = [rest[rest.length - 1], ...rest.slice(0, -1)];
  }
  return pairs;
}

function buildQuestions(): GenericQuestion[] {
  const used: Record<CareerKey, number> = {
    realistic: 0, investigative: 0, artistic: 0, social: 0, enterprising: 0, conventional: 0,
  };
  const next = (key: CareerKey) => SENTENCES[key][used[key]++];
  const pairs = roundRobinPairs();
  const passes = [pairs, pairs.map(([x, y]) => [y, x] as [CareerKey, CareerKey])];
  return passes.flat().map(([left, right]) => ({
    a: next(left),
    b: next(right),
    aScores: { [left]: 1 },
    bScores: { [right]: 1 },
  }));
}

