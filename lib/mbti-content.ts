export function getProfile(value: string) {
  return profiles[value.toLowerCase() as MbtiCode];
}

export function sharedLetters(a: MbtiCode, b: MbtiCode) {
  return a.toUpperCase().split("").filter((letter, index) => letter === b.toUpperCase()[index]).length;
}

